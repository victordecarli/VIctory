/// Opens `path` for reading; the file object owns the handle.
///
/// # Safety
///
/// `path` is null or points to a NUL-terminated UTF-16 path, `iid` is null
/// or valid for a read of a `Guid`, and `out` is null or valid for a write
/// of a pointer.
unsafe extern "system" fn open_file(
    _: Factory,
    path: *const u16,
    iid: *const Guid,
    out: Out,
) -> HRESULT {
    const GENERIC_READ: u32 = 0x8000_0000;
    const FILE_SHARE_READ: u32 = 1;
    const OPEN_EXISTING: u32 = 3;
    if path.is_null() {
        return E_INVALIDARG;
    }
    // Goes through `files`, so paths on our virtual drives work too.
    // SAFETY: `path` is non-null (checked above) and the title's
    // NUL-terminated path; the other pointers are null.
    let handle = unsafe {
        super::files::CreateFileW(
            path,
            GENERIC_READ,
            FILE_SHARE_READ,
            std::ptr::null(),
            OPEN_EXISTING,
            0,
            std::ptr::null_mut(),
        )
    };
    // SAFETY: non-null, and NUL-terminated, per this function's contract.
    let name = unsafe {
        let len = (0..).take_while(|&i| *path.add(i) != 0).count();
        String::from_utf16_lossy(std::slice::from_raw_parts(path, len))
    };
    if handle as isize == -1 {
        let error = std::io::Error::last_os_error();
        tracing::warn!(path = name, %error, "dstorage: opening a file failed");
        return from_win32(&error);
    }
    // SAFETY: as this function's contract gives them.
    tracing::info!(path = name, iid = unsafe { iid_text(iid) }, "dstorage: file opened");
    // SAFETY: a handle we just opened and nobody else owns.
    let file = unsafe { std::fs::File::from_raw_handle(handle) };
    let file = Instance::create(Object::new("dstorage file", &FILE_VTABLE), File { file });
    put(out, file)
}

