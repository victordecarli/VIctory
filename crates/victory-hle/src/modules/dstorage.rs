/// The factory interface Grand Theft Auto VI asks for.
const FACTORY: Guid =
    Guid::new(0x6295_9d11, 0xd45f, 0x4884, [0xa0, 0xa3, 0xf7, 0x86, 0x2e, 0xa2, 0x43, 0xae]);
const E_NOINTERFACE: HRESULT = 0x8000_4002_u32 as i32;
const E_OUTOFMEMORY: HRESULT = 0x8007_000E_u32 as i32;
/// `HRESULT_FROM_WIN32(ERROR_HANDLE_EOF)`: the source ends early.
const END_OF_FILE: HRESULT = 0x8007_0026_u32 as i32;
/// `HRESULT_FROM_WIN32(ERROR_INVALID_DATA)`: a bad compressed stream.
const INVALID_DATA: HRESULT = 0x8007_000D_u32 as i32;

type Out = *mut *mut c_void;

static FACTORY_OBJECT: Object = Object::new("dstorage factory", &FACTORY_VTABLE);

/// # Safety
///
/// `iid` is null or valid for a read of a `Guid`, and `out` is null or
/// valid for a write of a pointer.
pub unsafe extern "system" fn DStorageGetFactory(iid: *const Guid, out: Out) -> HRESULT {
    // SAFETY: `iid` is null or readable, per this function's contract.
    match unsafe { iid.as_ref() } {
        Some(&iid) if iid == FACTORY => {
            put(out, std::ptr::from_ref(&FACTORY_OBJECT).cast_mut().cast())
        }
        iid => {
            tracing::warn!(iid = ?iid.map(Guid::to_string), "DStorageGetFactory: unknown interface");
            E_NOINTERFACE
        }
    }
}

/// One of our objects with state: the runtime's object header (method
/// table first), a reference count, then `T`.
#[repr(C)]
struct Instance<T> {
    base: Object,
    refs: AtomicU32,
    state: T,
}

impl<T> Instance<T> {
    fn create(base: Object, state: T) -> *mut c_void {
        Box::into_raw(Box::new(Instance { base, refs: AtomicU32::new(1), state })).cast()
    }
}

/// # Safety
///
/// `this` is an instance this module created and has not yet freed.
unsafe extern "system" fn add_ref_instance<T>(this: *const Instance<T>) -> u32 {
    // SAFETY: a live instance, per this function's contract.
    unsafe { &*this }.refs.fetch_add(1, Ordering::Relaxed) + 1
}

/// # Safety
///
/// `this` is an instance this module created, holding the reference the
/// caller gives up; it must not be used after the last one is released.
unsafe extern "system" fn release<T>(this: *mut Instance<T>) -> u32 {
    // SAFETY: as above.
    let left = unsafe { &*this }.refs.fetch_sub(1, Ordering::AcqRel) - 1;
    if left == 0 {
        // SAFETY: the last reference; created by `Instance::create`.
        drop(unsafe { Box::from_raw(this) });
    }
    left
}

/// # Safety
///
/// `iid` is null or valid for a read of a `Guid`.
unsafe fn iid_text(iid: *const Guid) -> String {
    // SAFETY: `iid` is null or readable, per this function's contract.
    unsafe { iid.as_ref() }.map_or_else(|| "null".into(), Guid::to_string)
}

/// `HRESULT_FROM_WIN32` of a host error.
fn from_win32(error: &std::io::Error) -> HRESULT {
    error.raw_os_error().map_or(E_INVALIDARG, |e| (0x8007_0000 | (e as u32 & 0xffff)) as i32)
}

